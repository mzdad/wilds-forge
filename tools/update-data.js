// Downloads the Monster Hunter Wilds game data from the free mhdb API
// (https://docs.wilds.mhdb.io) and writes a slimmed-down copy to data.js.
//
// Run it again whenever the game gets an update:
//   node tools/update-data.js
//
// To only look, without changing data.js:
//   node tools/update-data.js --check
//
// Why a copy instead of asking the API live from the page?
// The page then works offline, loads instantly, and never breaks if the API is down.

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const CHECK_ONLY = process.argv.includes("--check");

const API = "https://wilds.mhdb.io";
const OUT = path.join(__dirname, "..", "data.js");

async function get(endpoint) {
	const response = await fetch(API + endpoint);
	if (!response.ok) {
		throw new Error(endpoint + " answered " + response.status);
	}
	return response.json();
}

// Armor the game only lets you wear whole (like the Akuma α collab set) has a telltale
// recipe: ONE recipe covers the whole set, so one piece lists materials and the other
// pieces list none. Free starter sets (Hope, Leather, Chainmail) list none on every piece,
// so they do not match. Returns the names of sets that match.
function findWholeSetCandidates(armor) {
	const sets = new Map();
	for (const piece of armor) {
		const name = piece.armorSet ? piece.armorSet.name : "";
		if (!sets.has(name)) {
			sets.set(name, []);
		}
		sets.get(name).push(piece);
	}
	const found = [];
	for (const [name, pieces] of sets) {
		const withMaterials = pieces.filter((p) => p.crafting && p.crafting.materials && p.crafting.materials.length > 0);
		if (name && pieces.length > 1 && withMaterials.length === 1) {
			found.push(name);
		}
	}
	return found;
}

// effects.js is written for the browser, so run it with a pretend window to read its list.
function knownWholeSets() {
	const sandbox = { window: {} };
	vm.createContext(sandbox);
	vm.runInContext(fs.readFileSync(path.join(__dirname, "..", "effects.js"), "utf8"), sandbox);
	return sandbox.window.WILDS_EFFECTS.wholeSetOnly || [];
}

async function main() {
	console.log("Downloading from " + API + " ...");
	const version = await get("/version");
	const skills = await get("/en/skills");
	const armor = await get("/en/armor");
	const decorations = await get("/en/decorations");
	const charms = await get("/en/charms");

	// Skills: keep the name, what kind it is, and what each level does.
	const slimSkills = skills.map((skill) => ({
		id: skill.id,
		name: skill.name,
		kind: skill.kind, // "armor", "weapon", "set" or "group"
		desc: skill.description || "",
		ranks: skill.ranks.map((rank) => ({
			level: rank.level,
			name: rank.name || "",
			desc: rank.description || "",
			pieces: rank.setPiecesRequired || 0,
		})),
	}));

	// Armor: one entry per piece. Skills become [skillId, level] pairs to save space.
	const slimArmor = armor.map((piece) => ({
		id: piece.id,
		name: piece.name,
		kind: piece.kind, // head, chest, arms, waist, legs
		rank: piece.rank, // "low" or "high"
		rarity: piece.rarity,
		defense: piece.defense.max,
		slots: piece.slots,
		set: piece.armorSet ? piece.armorSet.name : "",
		skills: piece.skills.map((rank) => [rank.skill.id, rank.level]),
	}));

	const slimDecorations = decorations.map((deco) => ({
		id: deco.id,
		name: deco.name,
		kind: deco.kind, // "armor" jewels go in armor, "weapon" jewels go in the weapon
		slot: deco.slot,
		skills: deco.skills.map((rank) => [rank.skill.id, rank.level]),
	}));

	// Charms come in levels (I, II, III ...). Each level is its own choice.
	// Random charms ("Unknown Charm" etc.) have no fixed skills, so they are left out.
	const slimCharms = [];
	for (const charm of charms) {
		if (charm.random) {
			continue;
		}
		for (const rank of charm.ranks) {
			if (rank.skills.length === 0) {
				continue;
			}
			slimCharms.push({
				id: rank.id,
				name: rank.name,
				rarity: rank.rarity,
				skills: rank.skills.map((s) => [s.skill.id, s.level]),
			});
		}
	}

	const data = {
		version: version.version,
		skills: slimSkills,
		armor: slimArmor,
		decorations: slimDecorations,
		charms: slimCharms,
	};

	const text =
		"// Generated by tools/update-data.js from the mhdb API. Do not edit by hand.\n" +
		"window.WILDS_DATA = " + JSON.stringify(data) + ";\n";
	if (CHECK_ONLY) {
		console.log("--check: data.js was not changed.");
	} else {
		fs.writeFileSync(OUT, text, "utf8");
	}

	console.log("Game data from " + version.version);
	console.log(slimSkills.length + " skills, " + slimArmor.length + " armor pieces, " +
		slimDecorations.length + " decorations, " + slimCharms.length + " charms");
	if (!CHECK_ONLY) {
		console.log("Wrote " + OUT + " (" + Math.round(text.length / 1024) + " KB)");
	}

	// Look for armor that can only be worn as a whole set (see findWholeSetCandidates).
	const known = knownWholeSets();
	const candidates = findWholeSetCandidates(armor);
	const missing = candidates.filter((name) => !known.includes(name));
	const stale = known.filter((name) => !candidates.includes(name));
	console.log("Whole-set armor in effects.js: " + (known.join(", ") || "none"));
	if (missing.length) {
		console.log("\nCHECK THIS: " + missing.join(", ") + " has the same kind of recipe as Akuma α (one recipe for the whole set).");
		console.log("If the game wears all its pieces together, add the name to wholeSetOnly in effects.js.");
	}
	if (stale.length) {
		console.log("\nNote: " + stale.join(", ") + " is in wholeSetOnly but no longer has the one-recipe pattern. Worth a look.");
	}
	if (!missing.length && !stale.length) {
		console.log("No other set has the Akuma-style recipe, so nothing else needs the whole-set rule.");
	}
}

// Run the download only when started directly (node tools/update-data.js). The tests
// load this file just to try findWholeSetCandidates.
if (require.main === module) {
	main().catch((error) => {
		console.error("Failed: " + error.message);
		process.exit(1);
	});
}

module.exports = { findWholeSetCandidates };
